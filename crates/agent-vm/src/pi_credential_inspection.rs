    proptest! {
        /// Changing one non-placeholder credential value for another leaves the
        /// *rendered* report identical: the second value's bytes never reach it.
        #[test]
        fn swapping_a_non_placeholder_value_leaves_the_report_unchanged(
            a in "[A-Za-z0-9]{1,24}",
            b in "[A-Za-z0-9]{1,24}",
        ) {
            prop_assume!(a != b);
            prop_assume!(!is_known_placeholder(&a) && !is_known_placeholder(&b));
            let first = auth_findings(&format!(r#"{{"p":{{"type":"api_key","key":"{a}"}}}}"#));
            let second = auth_findings(&format!(r#"{{"p":{{"type":"api_key","key":"{b}"}}}}"#));
            prop_assert_eq!(first, second);
        }

        /// Any byte mutation of a placeholder is not the placeholder.
        #[test]
        fn mutating_a_placeholder_is_not_a_placeholder(suffix in "[A-Za-z0-9]{1,8}") {
            for placeholder in crate::secrets::ALL_PLACEHOLDERS {
                let appended = format!("{}{}", placeholder, suffix);
                let prepended = format!("{}{}", suffix, placeholder);
                prop_assert!(!is_known_placeholder(&appended));
                prop_assert!(!is_known_placeholder(&prepended));
            }
        }

        /// A provider id outside the accepted grammar never reaches output:
        /// every one collapses to the fixed `<unrecognized-provider>` label.
        #[test]
        fn unsafe_provider_ids_never_reach_output(raw in ".{1,80}") {
            prop_assume!(!provider_id_is_safe(&raw));
            let quoted = serde_json::to_string(&raw).unwrap();
            let findings = auth_findings(&format!(
                r#"{{{quoted}:{{"type":"api_key","key":"real"}}}}"#
            ));
            prop_assert_eq!(findings.len(), 1);
            prop_assert_eq!(
                finding_line(&findings[0]),
                "auth.json: provider=<unrecognized-provider> type=api_key fields=key"
            );
        }

        /// A custom header name is never echoed — only `headers.<custom>`.
        #[test]
        fn custom_header_names_never_reach_output(name in ".{1,40}") {
            prop_assume!(!name.eq_ignore_ascii_case("authorization"));
            let quoted = serde_json::to_string(&name).unwrap();
            let body = format!(
                r#"{{"providers":{{"demo":{{"headers":{{{quoted}:"secret-value"}}}}}}}}"#
            );
            let findings = models_findings(&body);
            prop_assert_eq!(
                findings.iter().map(finding_line).collect::<Vec<_>>(),
                vec![
                    "models.json: provider=demo type=configuration fields=headers.<custom>"
                        .to_string()
                ]
            );
        }
    }
