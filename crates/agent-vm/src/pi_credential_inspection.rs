// Acquisition

fn inspect_location(
    guest: &GuestStateDir,
    location: Location,
    files: &mut Vec<PiFileState>,
    sink: &mut FindingSink,
) {
    inspect_location_at(guest, location, Path::new("pi"), files, sink);
}

/// The legacy pre-#96 layout held a real `<state>/home/.pi` directory that the
/// compiled guest-HOME link now maps away. It is only scanned when that entry
/// is a **real directory**; the usual compiled mapping is a final symlink,
/// which must not be followed (following it would scan the same bytes twice
/// and would resolve a guest-planted redirect).
fn inspect_legacy(guest: &GuestStateDir, files: &mut Vec<PiFileState>, sink: &mut FindingSink) {
    match guest.entry_type(Path::new("home/.pi")) {
        Ok(Some(EntryType::Directory)) => {
            inspect_location_at(guest, Location::Legacy, Path::new("home/.pi"), files, sink);
        }
        Ok(Some(EntryType::Symlink)) | Ok(None) => {}
        Ok(Some(_)) | Err(_) => {
            for file in PiFile::ALL {
                files.push(PiFileState {
                    location: Location::Legacy,
                    file,
                    status: PiFileStatus::Uninspectable,
                });
                sink.push(uninspectable_finding(Location::Legacy, file));
            }
        }
    }
}

fn inspect_location_at(
    guest: &GuestStateDir,
    location: Location,
    root: &Path,
    files: &mut Vec<PiFileState>,
    sink: &mut FindingSink,
) {
    for file in PiFile::ALL {
        let relative = root.join(file.protected().pi_home_relative());
        match guest.read(&relative) {
            Ok(Some(bytes)) => {
                match file {
                    PiFile::Auth => inspect_auth(&bytes, location, sink),
                    PiFile::Models => inspect_models(&bytes, location, sink),
                }
                files.push(PiFileState {
                    location,
                    file,
                    status: PiFileStatus::Inspected,
                });
            }
            Ok(None) => files.push(PiFileState {
                location,
                file,
                status: PiFileStatus::Absent,
            }),
            Err(_) => {
                // Never log the discarded anyhow context: it can carry a path
                // and OS detail. Collapse to the fixed category.
                files.push(PiFileState {
                    location,
                    file,
                    status: PiFileStatus::Uninspectable,
                });
                sink.push(uninspectable_finding(location, file));
            }
        }
    }
}

