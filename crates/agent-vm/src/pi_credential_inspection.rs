//! Read-only structural inspection of the project-scoped guest Pi credential
//! files (`docs/adr/0011-pi-mixed-credential-ownership.md`, issue #93).
//!
//! Pi's user state is not checkout `.pi/`. Every shipped tool sees the same
//! project-scoped guest home mapping: guest `~/.pi` → `/agent-vm-state/pi` →
//! host `<project-state>/pi`. A guest can therefore leave a credential that any
//! later tool in this project can read, and a launch should say so before the
//! guest runs.
//!
//! This module is a *structural classifier*, not a resolver. Its defining
//! property is that it never resolves a credential: it does not run
//! `!command` values, expand environment references, refresh OAuth, import a
//! host credential, construct a proxy, or write/remove/rename anything. It
//! reads the two files with the descriptor-anchored, no-follow, bounded
//! [`GuestStateDir`] reader and returns a report containing only safe data:
//! a validated provider identifier, a closed credential-kind label, closed
//! field labels, and fixed reason labels. Raw JSON, credential bytes,
//! environment names, commands, model IDs and URLs never leave this module.
//!
//! Reporting is **not** ownership authorization. "Contains no secret bytes"
//! is weaker than "this exact provider entry was generated by agent-vm"; the
//! downstream reconciliation (#94) must consume a stronger per-provider
//! ownership predicate, not [`PiCredentialReport`]. See ADR-0011.
//!
//! The host Pi files `~/.pi/agent/{auth,models}.json` are separately protected
//! by ADR-0020 and are deliberately outside this module's scope.

