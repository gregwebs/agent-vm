fn inspect_auth(bytes: &[u8], location: Location, sink: &mut FindingSink) {
    let json = match parse_document(bytes) {
        Some(json) => json,
        None => {
            sink.push(Finding::new(
                location,
                PiFile::Auth,
                SafeProviderId::Unknown,
                CredentialKind::Unknown,
                BTreeSet::new(),
                FindingReason::Malformed,
            ));
            return;
        }
    };
    let Some(entries) = json.as_object() else {
        sink.push(Finding::new(
            location,
            PiFile::Auth,
            SafeProviderId::Unknown,
            CredentialKind::Unknown,
            BTreeSet::new(),
            FindingReason::Malformed,
        ));
        return;
    };
    for (name, entry) in entries {
        if let Some(found) = classify_auth_entry(location, name, entry) {
            sink.push(found);
        }
    }
}

fn classify_auth_entry(location: Location, name: &str, entry: &Json) -> Option<Finding> {
    let provider = SafeProviderId::new(name);
    let Some(members) = entry.as_object() else {
        return Some(Finding::new(
            location,
            PiFile::Auth,
            provider,
            CredentialKind::Unknown,
            BTreeSet::new(),
            FindingReason::Malformed,
        ));
    };
    let type_value = member(members, "type").and_then(Json::as_str);
    let kind = match type_value {
        Some("api_key") => CredentialKind::ApiKey,
        Some("oauth") => CredentialKind::OAuth,
        _ => CredentialKind::Unknown,
    };
    // An absent or unrecognized `type` is itself an unrecognized entry: there
    // is no way to know which fields are credential-bearing and which are
    // merely extra.
    let mut unrecognized = !matches!(type_value, Some("api_key") | Some("oauth"));
    let mut malformed = false;
    let mut fields: BTreeSet<Field> = BTreeSet::new();

    for (key, value) in members {
        match key.as_str() {
            "type" => {}
            "key" if kind == CredentialKind::ApiKey => match value {
                // The pinned Pi accepts an absent or empty key with no
                // credential bytes; an exact known placeholder is also quiet.
                Json::String(text) if text.is_empty() || is_known_placeholder(text) => {}
                _ => {
                    fields.insert(Field::Key);
                }
            },
            // `env` is an object of string-valued references in the pinned
            // schema. Any nonempty map (or a value of the wrong shape) is
            // potentially sensitive; its names and values are never reported.
            "env" if kind == CredentialKind::ApiKey => match value {
                Json::Object(entries) if entries.is_empty() => {}
                _ => {
                    fields.insert(Field::Env);
                }
            },
            "access" if kind == CredentialKind::OAuth => {
                if !string_is_placeholder(value) {
                    fields.insert(Field::Access);
                }
            }
            "refresh" if kind == CredentialKind::OAuth => {
                if !string_is_placeholder(value) {
                    fields.insert(Field::Refresh);
                }
            }
            "expires" if kind == CredentialKind::OAuth => {
                if value.as_finite_number().is_none() {
                    fields.insert(Field::Expires);
                    malformed = true;
                }
            }
            other => match credential_field(other) {
                Some(field) => {
                    if !string_is_placeholder(value) {
                        fields.insert(field);
                    }
                }
                None => {
                    // Extra members on a credential entry are never ignored:
                    // #91 plans an `accountId` producer, and a future landed
                    // producer must extend this rule and its tests together.
                    unrecognized = true;
                    fields.insert(Field::Other);
                }
            },
        }
    }

    // Required OAuth shape: string access, string refresh, finite expires.
    if kind == CredentialKind::OAuth {
        for (required, field) in [
            ("access", Field::Access),
            ("refresh", Field::Refresh),
            ("expires", Field::Expires),
        ] {
            if member(members, required).is_none() {
                fields.insert(field);
                malformed = true;
            }
        }
    }

    if fields.is_empty() && !unrecognized && !malformed {
        return None;
    }
    let reason = if malformed {
        FindingReason::Malformed
    } else if unrecognized {
        FindingReason::Unrecognized
    } else {
        FindingReason::GuestManaged
    };
    Some(Finding::new(
        location,
        PiFile::Auth,
        provider,
        kind,
        fields,
        reason,
    ))
}

